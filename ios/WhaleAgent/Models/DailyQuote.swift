    static func slotIndex(at date: Date, calendar: Calendar = .current) -> Int {
        let day = calendar.ordinality(of: .day, in: .era, for: date) ?? 0
        let hour = calendar.component(.hour, from: date)
        let slot = min(slotsPerDay - 1, max(0, hour / 6))
        // 用绝对时段序号做排列：37 与 120 互质，任意连续 120 个时段正好覆盖整池，
        // 因此无论从哪一天开始，连续 30 天的 120 条都不会重复。
        let globalSlot = day * slotsPerDay + slot
        return ((globalSlot * 37) % pool.count + pool.count) % pool.count
    }

    static func text(at date: Date, calendar: Calendar = .current) -> String {
        let hour = calendar.component(.hour, from: date)
        let opener: String
        switch hour {
        case 0..<6: opener = "夜深了"
        case 6..<9: opener = "早上好"
        case 9..<12: opener = "上午好"
        case 12..<14: opener = "中午好"
        case 14..<18: opener = "下午好"
        case 18..<22: opener = "晚上好"
        default: opener = "夜深了"
        }
        return "BOSS，\(opener)。\(pool[slotIndex(at: date, calendar: calendar)])"
    }
